#!/usr/bin/env python3
"""Check the Help Center's answers (shared/help/help.json) and its search fixture.

    python3 tools/check_help.py         # check help.json and that shared/fixtures/help-search.json is current
    python3 tools/check_help.py --gen   # rewrite the fixture after changing the answers or the search

Every answer needs an id, at least one platform, and a title, text and keywords in English and Arabic; the app's old
name must not appear. The search mirrors NMCore HelpCenter.search (same normalizer as tools/reference_search.py), and
the fixture holds what it returns for real questions in both languages, which NMCoreTests checks too.
"""
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from reference_search import normalize  # noqa: E402

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
HELP = os.path.join(ROOT, "shared", "help", "help.json")
FIXTURE = os.path.join(ROOT, "shared", "fixtures", "help-search.json")
PLATFORMS = {"phone", "tv"}

STOPWORDS = set(normalize(
    "the a an my i is are to of in on and or how do does what why it it's can't don't doesn't won't app me with for "
    "ما في من على لا كيف هل عن إلى الى أن ان لماذا لم هذا التطبيق عندي"))

# Real questions people ask, and the platform they ask on.
QUERIES = [
    ("phone", "the adhan doesn't play"),
    ("phone", "no notifications"),
    ("phone", "prayer times are wrong"),
    ("phone", "asr time is different from my mosque"),
    ("phone", "qibla direction"),
    ("phone", "how do I turn off the ad blocker"),
    ("phone", "quran stops"),
    ("phone", "is this a fatwa"),
    ("phone", "what data do you collect"),
    ("phone", "widget"),
    ("phone", "samsung tv"),
    ("phone", "الأذان لا يعمل"),
    ("phone", "المواقيت غير صحيحة"),
    ("phone", "اتجاه القبلة"),
    ("phone", "إيقاف حجب الإعلانات"),
    ("phone", "القرآن لا يشتغل"),
    ("phone", "خصوصية بياناتي"),
    ("phone", "المدينة خطأ"),
    ("tv", "qibla"),
    ("tv", "wrong city"),
    ("tv", "شاشة المسجد"),
    ("phone", "the"),
    ("phone", ""),
]


def search(data, query, platform):
    words = [w for w in normalize(query) if w not in STOPWORDS]
    articles = [a for a in data["articles"] if platform in a["platforms"]]
    if not words:
        return articles
    scored = []
    for i, a in enumerate(articles):
        strong = set(normalize(" ".join([a["title"]["en"], a["title"]["ar"], " ".join(a["keywords"]["en"]),
                                         " ".join(a["keywords"]["ar"])])))
        weak = set(normalize(a["body"]["en"] + " " + a["body"]["ar"]))
        score = 0
        for w in words:
            if w in strong:
                score += 3
            elif len(w) >= 3 and any(s.startswith(w) for s in strong):
                score += 2
            elif w in weak:
                score += 1
        if score:
            scored.append((-score, i, a))
    return [a for _, _, a in sorted(scored, key=lambda x: (x[0], x[1]))]


def validate(data):
    errors = []
    contact = data.get("contact", {})
    if not re.fullmatch(r"[^@\s]+@[^@\s]+\.[a-z]+", contact.get("email", "")):
        errors.append("contact.email is not an email address")
    if set(contact) != {"email"}:
        errors.append("contact holds only the email: reports and ideas stay in the apps and the website, not WhatsApp")
    seen = set()
    for a in data.get("articles", []):
        aid = a.get("id", "")
        if not re.fullmatch(r"[a-z0-9-]+", aid) or aid in seen:
            errors.append(f"bad or repeated id {aid!r}")
        seen.add(aid)
        if not a.get("platforms") or set(a["platforms"]) - PLATFORMS:
            errors.append(f"{aid}: platforms must be from {sorted(PLATFORMS)}")
        for field in ("title", "body", "keywords"):
            for lang in ("en", "ar"):
                v = a.get(field, {}).get(lang)
                if not v:
                    errors.append(f"{aid}: missing {field}.{lang}")
        for lang in ("en", "ar"):
            text = a.get("title", {}).get(lang, "") + " " + a.get("body", {}).get(lang, "")
            if re.search(r"Near Mosque|أقرب مسجد|nearmosque", text):
                errors.append(f"{aid}: uses the old app name in {lang}")
        if a.get("body", {}).get("ar") and not re.search(r"[؀-ۿ]", a["body"]["ar"]):
            errors.append(f"{aid}: body.ar has no Arabic")
    if not data.get("articles"):
        errors.append("no articles")
    return errors


def fixture(data):
    return {
        "_comment": "Generated by tools/check_help.py --gen. NMCore HelpCenter.search must return these ids, in this order.",
        "cases": [{"platform": p, "query": q, "ids": [a["id"] for a in search(data, q, p)]} for p, q in QUERIES],
    }


def main():
    data = json.load(open(HELP, encoding="utf-8"))
    errors = validate(data)
    want = json.dumps(fixture(data), ensure_ascii=False, indent=1) + "\n"
    if "--gen" in sys.argv:
        open(FIXTURE, "w", encoding="utf-8").write(want)
    elif not os.path.exists(FIXTURE) or open(FIXTURE, encoding="utf-8").read() != want:
        errors.append("shared/fixtures/help-search.json is out of date: run python3 tools/check_help.py --gen")
    for e in errors:
        print("error:", e)
    if errors:
        sys.exit(1)
    print(f"{len(data['articles'])} help answers ok; {len(QUERIES)} search cases")


if __name__ == "__main__":
    main()
